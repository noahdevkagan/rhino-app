import Cocoa
import Carbon

enum ClipboardUtil {
    /// Copies text to the clipboard. Used only as an optional independent stash;
    /// insertion into the focused app is done by `TextInserter`, not the clipboard.
    static func copyToClipboard(_ text: String, to pasteboard: NSPasteboard = .general) {
        pasteboard.declareTypes([.string], owner: nil)
        pasteboard.setString(text, forType: .string)
    }

    // MARK: - Borrow-and-restore (paste mode with "Copy to clipboard" off — #44)

    /// The pasteboard's full contents (every item, every type), so it can be put back
    /// after the clipboard is borrowed as the ⌘V paste vehicle.
    struct Snapshot {
        let items: [[NSPasteboard.PasteboardType: Data]]
    }

    static func snapshot(of pasteboard: NSPasteboard = .general) -> Snapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.reduce(into: [NSPasteboard.PasteboardType: Data]()) { acc, type in
                acc[type] = item.data(forType: type)
            }
        }
        return Snapshot(items: items)
    }

    /// Writes a snapshot back, replacing the pasteboard's current contents. `markTransient` adds
    /// `org.nspasteboard.TransientType` so clipboard managers don't log the put-back as a fresh copy.
    static func restore(_ snapshot: Snapshot, to pasteboard: NSPasteboard = .general,
                        markTransient: Bool = false) {
        pasteboard.clearContents()
        guard !snapshot.items.isEmpty else { return }
        let items = snapshot.items.map { typeMap -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in typeMap { item.setData(data, forType: type) }
            return item
        }
        if markTransient, let first = items.first, first.data(forType: transientType) == nil {
            first.setData(Data(), forType: transientType)
        }
        pasteboard.writeObjects(items)
    }

    /// The earliest the previous contents come back after a borrow, even when the paste target
    /// read the text sooner: a clipboard manager that ignores the nspasteboard.org markers may be
    /// the first reader, and this keeps such setups no worse than the old fixed one-second restore.
    static let borrowRestoreDelay: TimeInterval = 1.0

    /// After the borrowed text is first read, how long it stays before the restore, so an app that
    /// reads the string more than once for one paste gets the same text each time.
    static let borrowReadGrace: TimeInterval = 0.25

    /// If nobody reads the borrowed text, restore after this long anyway. The ⌘V can sit queued
    /// behind a busy page for well over a second: Chrome on claude.ai pasted the user's previous
    /// clipboard instead of the dictation under the old fixed one-second restore (Deepak, 0.1.41).
    static let borrowUnreadFallback: TimeInterval = 5.0

    /// The nspasteboard.org conventions a borrowed (temporary) write carries so clipboard managers
    /// skip it: Transient (about to be replaced), Concealed (do not show or store), AutoGenerated
    /// (not something the user copied). Managers differ in which ones they honor, so set all three.
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let borrowMarkerTypes: [NSPasteboard.PasteboardType] = [
        transientType,
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    /// Supplies the borrowed text lazily, so the first app to actually read it (the paste target
    /// servicing the ⌘V) tells us the paste has happened and the restore can follow.
    private final class BorrowedText: NSObject, NSPasteboardItemDataProvider {
        let text: String
        /// Main-thread only. Fired once, on the first read.
        var onFirstRead: (() -> Void)?

        init(_ text: String) { self.text = text }

        func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem,
                        provideDataForType type: NSPasteboard.PasteboardType) {
            item.setString(text, forType: type)
            DispatchQueue.main.async { [weak self] in
                guard let self, let onFirstRead = self.onFirstRead else { return }
                self.onFirstRead = nil
                onFirstRead()
            }
        }
    }

    /// A borrow whose restore hasn't fired yet.
    private final class PendingBorrow {
        let saved: Snapshot
        let text: BorrowedText
        var restore: DispatchWorkItem?

        init(saved: Snapshot, text: BorrowedText) {
            self.saved = saved
            self.text = text
        }

        /// Stops this borrow from restoring or reacting to reads (it was restored or superseded).
        func retire() {
            restore?.cancel()
            restore = nil
            text.onFirstRead = nil
        }
    }

    /// Borrows whose restore hasn't fired yet, keyed by pasteboard name. A borrow that lands while
    /// another is still pending must NOT snapshot — the pasteboard currently holds the previous
    /// borrow's transcription, and restoring that later would overwrite the user's contents with
    /// dictated text, the very thing "Copy to clipboard" off exists to prevent. Instead it inherits
    /// the pending borrow's snapshot and retires it, so any number of overlapping borrows collapse
    /// into a single restore of the original contents. Main-thread only, like every caller (the
    /// restore timers and read callbacks are on the main queue too, so there is no interleaving).
    private static var pendingBorrows: [NSPasteboard.Name: PendingBorrow] = [:]

    /// Puts `text` on the pasteboard just long enough for `paste` (a synthetic ⌘V) to be serviced,
    /// then restores the previous contents — for when the user opted out of keeping transcriptions
    /// on the clipboard and it's only borrowed as the paste vehicle (#44). The restore waits for
    /// the text to be read: `readGrace` after the first read, never before `delay`, and at
    /// `unreadFallback` if nothing reads it. A fixed timer lost the race to slow targets, which
    /// then pasted the old clipboard. The restore is skipped if anything else writes to the
    /// pasteboard meanwhile (a user copy, a clipboard manager): newer content wins over our
    /// restore. Overlapping borrows — a dictation insert followed by the paste-last shortcut —
    /// coalesce onto the first borrow's snapshot, so the user's clipboard comes back no matter how
    /// many borrows stacked up.
    static func borrowForPaste(_ text: String,
                               on pasteboard: NSPasteboard = .general,
                               restoreAfter delay: TimeInterval = borrowRestoreDelay,
                               readGrace: TimeInterval = borrowReadGrace,
                               unreadFallback: TimeInterval = borrowUnreadFallback,
                               paste: () -> Void) {
        let name = pasteboard.name
        let saved: Snapshot
        if let pending = pendingBorrows[name] {
            pending.retire()
            saved = pending.saved
        } else {
            saved = snapshot(of: pasteboard)
        }
        // Clipboard managers can observe the temporary text before restoration. Publish the
        // nspasteboard.org markers together with the text, never an unmarked intermediate
        // copy, so Maccy, Paste, Raycast and other conforming managers leave it out of history.
        // The markers are checked by type, so reading them never counts as the paste.
        let provider = BorrowedText(text)
        let item = NSPasteboardItem()
        for marker in borrowMarkerTypes { item.setData(Data(), forType: marker) }
        _ = item.setDataProvider(provider, forTypes: [.string])
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        let borrowChangeCount = pasteboard.changeCount
        let borrowedAt = DispatchTime.now()

        let pending = PendingBorrow(saved: saved, text: provider)
        pendingBorrows[name] = pending
        func scheduleRestore(at deadline: DispatchTime) {
            pending.restore?.cancel()
            let restoreItem = DispatchWorkItem {
                guard pendingBorrows[name] === pending else { return }
                pendingBorrows[name] = nil
                pending.retire()
                guard pasteboard.changeCount == borrowChangeCount else { return }
                // The put-back is the user's own earlier copy, which their clipboard manager
                // already logged when they made it. Mark it transient so it isn't logged again as
                // a new entry after every dictation. This never hides a genuine new copy: anything
                // written during the borrow changes changeCount and the restore is skipped above.
                Self.restore(saved, to: pasteboard, markTransient: true)
            }
            pending.restore = restoreItem
            DispatchQueue.main.asyncAfter(deadline: deadline, execute: restoreItem)
        }
        provider.onFirstRead = {
            guard pendingBorrows[name] === pending else { return }
            scheduleRestore(at: max(borrowedAt + delay, DispatchTime.now() + readGrace))
        }
        scheduleRestore(at: borrowedAt + unreadFallback)
        paste()
    }

    // MARK: - Input source helpers (used by keyboard-layout tests)

    static func getCurrentInputSourceID() -> String? {
        guard let inputSource = TISCopyCurrentKeyboardInputSource()?.takeRetainedValue(),
              let idPtr = TISGetInputSourceProperty(inputSource, kTISPropertyInputSourceID)
        else { return nil }
        return Unmanaged<CFString>.fromOpaque(idPtr).takeUnretainedValue() as String
    }

    static func switchToInputSource(withID targetID: String) -> Bool {
        guard let sourceList = TISCreateInputSourceList(nil, false)?.takeRetainedValue() as? [TISInputSource] else {
            return false
        }

        for source in sourceList {
            guard let idPtr = TISGetInputSourceProperty(source, kTISPropertyInputSourceID) else { continue }
            let sourceID = Unmanaged<CFString>.fromOpaque(idPtr).takeUnretainedValue() as String

            if sourceID.contains(targetID) || targetID.contains(sourceID) || sourceID == targetID {
                let result = TISSelectInputSource(source)
                usleep(100000) // 100ms delay for layout switch
                return result == noErr
            }
        }
        return false
    }

    static func getAvailableInputSources() -> [String] {
        guard let sourceList = TISCreateInputSourceList(nil, false)?.takeRetainedValue() as? [TISInputSource] else {
            return []
        }

        var result: [String] = []
        for source in sourceList {
            guard let idPtr = TISGetInputSourceProperty(source, kTISPropertyInputSourceID),
                  let selectablePtr = TISGetInputSourceProperty(source, kTISPropertyInputSourceIsSelectCapable)
            else { continue }

            let isSelectable = unsafeBitCast(selectablePtr, to: CFBoolean.self) == kCFBooleanTrue
            if isSelectable {
                let sourceID = Unmanaged<CFString>.fromOpaque(idPtr).takeUnretainedValue() as String
                result.append(sourceID)
            }
        }
        return result
    }
}
