import AppKit
import XCTest

@testable import OpenSuperWhisper

/// Covers the pasteboard snapshot/restore behind paste mode with "Copy to clipboard" off (#44),
/// where the clipboard is only borrowed as the ⌘V vehicle and must be given back. Runs against a
/// private named pasteboard so the developer's real clipboard is never touched.
final class ClipboardRestoreTests: XCTestCase {

    private var pasteboard: NSPasteboard!

    override func setUp() {
        super.setUp()
        pasteboard = NSPasteboard(name: NSPasteboard.Name("OpenSuperWhisperTests." + UUID().uuidString))
    }

    override func tearDown() {
        pasteboard.releaseGlobally()
        pasteboard = nil
        super.tearDown()
    }

    // MARK: - snapshot / restore

    func testSnapshotRestoreRoundtripsString() {
        ClipboardUtil.copyToClipboard("original", to: pasteboard)
        let snapshot = ClipboardUtil.snapshot(of: pasteboard)

        ClipboardUtil.copyToClipboard("transcription", to: pasteboard)
        ClipboardUtil.restore(snapshot, to: pasteboard)

        XCTAssertEqual(pasteboard.string(forType: .string), "original")
    }

    func testSnapshotRestorePreservesEveryTypeOfAnItem() {
        // An item carrying several representations (e.g. rich text copied from a browser)
        // must come back whole, not just its plain-string face.
        let blobType = NSPasteboard.PasteboardType("com.example.blob")
        let item = NSPasteboardItem()
        item.setString("styled", forType: .string)
        item.setData(Data([1, 2, 3]), forType: blobType)
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        let snapshot = ClipboardUtil.snapshot(of: pasteboard)

        ClipboardUtil.copyToClipboard("transcription", to: pasteboard)
        ClipboardUtil.restore(snapshot, to: pasteboard)

        XCTAssertEqual(pasteboard.string(forType: .string), "styled")
        XCTAssertEqual(pasteboard.pasteboardItems?.first?.data(forType: blobType), Data([1, 2, 3]))
    }

    func testRestoreOfEmptySnapshotLeavesPasteboardEmpty() {
        pasteboard.clearContents()
        let empty = ClipboardUtil.snapshot(of: pasteboard)

        ClipboardUtil.copyToClipboard("transcription", to: pasteboard)
        ClipboardUtil.restore(empty, to: pasteboard)

        XCTAssertNil(pasteboard.string(forType: .string))
    }

    // MARK: - borrowForPaste

    func testBorrowForPasteHasTextOnPasteboardDuringPaste() {
        ClipboardUtil.copyToClipboard("original", to: pasteboard)

        var textDuringPaste: String?
        ClipboardUtil.borrowForPaste("transcription", on: pasteboard, restoreAfter: 0.05, unreadFallback: 0.05) {
            textDuringPaste = pasteboard.string(forType: .string)
            // The nspasteboard.org markers clipboard managers skip on: they must accompany the
            // text when paste runs, on the same item.
            for raw in ["org.nspasteboard.TransientType",
                        "org.nspasteboard.ConcealedType",
                        "org.nspasteboard.AutoGeneratedType"] {
                let marker = NSPasteboard.PasteboardType(raw)
                XCTAssertTrue(pasteboard.types?.contains(marker) == true, raw)
                XCTAssertNotNil(pasteboard.pasteboardItems?.first?.data(forType: marker), raw)
            }
        }

        XCTAssertEqual(textDuringPaste, "transcription")
    }

    func testExplicitCopyRemainsVisibleToClipboardHistory() {
        ClipboardUtil.copyToClipboard("transcription", to: pasteboard)

        XCTAssertEqual(pasteboard.string(forType: .string), "transcription")
        for marker in ClipboardUtil.borrowMarkerTypes {
            XCTAssertFalse(pasteboard.types?.contains(marker) == true, marker.rawValue)
        }
    }

    // MARK: - "Copy to clipboard" default (Oct 2026 reports)

    func testCopyToClipboardDefaultsOffWhenNeverChosen() {
        let store = DefaultsStore.current
        let saved = store.object(forKey: "autoCopyToClipboard")
        defer { store.set(saved, forKey: "autoCopyToClipboard") }

        store.removeObject(forKey: "autoCopyToClipboard")
        XCTAssertFalse(AppPreferences.shared.autoCopyToClipboard,
                       "paste mode should borrow and restore the clipboard unless the user opted in")
    }

    func testExplicitCopyToClipboardChoiceIsKept() {
        let store = DefaultsStore.current
        let saved = store.object(forKey: "autoCopyToClipboard")
        defer { store.set(saved, forKey: "autoCopyToClipboard") }

        store.set(true, forKey: "autoCopyToClipboard")
        XCTAssertTrue(AppPreferences.shared.autoCopyToClipboard)
        store.set(false, forKey: "autoCopyToClipboard")
        XCTAssertFalse(AppPreferences.shared.autoCopyToClipboard)
    }

    func testBorrowForPasteRestoresPreviousContentsAfterDelay() {
        ClipboardUtil.copyToClipboard("original", to: pasteboard)

        ClipboardUtil.borrowForPaste("transcription", on: pasteboard, restoreAfter: 0.05, unreadFallback: 0.05) {}

        let restoreWindowElapsed = expectation(description: "restore window elapsed")
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) { restoreWindowElapsed.fulfill() }
        wait(for: [restoreWindowElapsed], timeout: 2)
        XCTAssertEqual(pasteboard.string(forType: .string), "original")
        // The put-back is marked transient so clipboard managers don't log the user's own copy a
        // second time, but it carries none of the "hide this" markers the borrowed text had.
        XCTAssertTrue(pasteboard.types?.contains(ClipboardUtil.transientType) == true)
        XCTAssertFalse(pasteboard.types?.contains(
            NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")) == true)
        XCTAssertFalse(pasteboard.types?.contains(
            NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")) == true)
    }

    func testPlainRestoreAddsNoMarker() {
        ClipboardUtil.copyToClipboard("original", to: pasteboard)
        let snapshot = ClipboardUtil.snapshot(of: pasteboard)
        ClipboardUtil.restore(snapshot, to: pasteboard)
        XCTAssertFalse(pasteboard.types?.contains(ClipboardUtil.transientType) == true)
    }

    // MARK: - TranscriptInserter with auto-paste off (PR #103 review)

    @MainActor
    func testAutoPasteOffPutsTextOnClipboardEvenWithCopyToClipboardOff() {
        let prefs = AppPreferences.shared
        let savedPaste = prefs.autoPasteTranscription
        let savedCopy = prefs.autoCopyToClipboard
        let savedBoard = TranscriptInserter.pasteboard
        prefs.autoPasteTranscription = false
        prefs.autoCopyToClipboard = false
        TranscriptInserter.pasteboard = pasteboard
        defer {
            prefs.autoPasteTranscription = savedPaste
            prefs.autoCopyToClipboard = savedCopy
            TranscriptInserter.pasteboard = savedBoard
        }
        ClipboardUtil.copyToClipboard("original", to: pasteboard)

        let outcome = TranscriptInserter.insert("dictated", honorAutoPastePreference: true)

        XCTAssertEqual(outcome, .skipped)
        // Clipboard is how an auto-paste-off user receives the text: a normal, unmarked copy.
        XCTAssertEqual(pasteboard.string(forType: .string), "dictated")
        for marker in ClipboardUtil.borrowMarkerTypes {
            XCTAssertFalse(pasteboard.types?.contains(marker) == true, marker.rawValue)
        }
    }

    func testBorrowForPasteSkipsRestoreWhenSomethingElseWroteMeanwhile() {
        ClipboardUtil.copyToClipboard("original", to: pasteboard)

        ClipboardUtil.borrowForPaste("transcription", on: pasteboard, restoreAfter: 0.05, unreadFallback: 0.05) {}
        ClipboardUtil.copyToClipboard("user copy in between", to: pasteboard)

        let restoreWindowElapsed = expectation(description: "restore window elapsed")
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) { restoreWindowElapsed.fulfill() }
        wait(for: [restoreWindowElapsed], timeout: 2)
        XCTAssertEqual(pasteboard.string(forType: .string), "user copy in between")
    }

    // MARK: - Restore waits for the paste target to read (Deepak, 0.1.41)

    /// Waits on the main run loop, so restore timers and read callbacks can fire.
    private func spin(_ seconds: TimeInterval) {
        let elapsed = expectation(description: "waited \(seconds)s")
        DispatchQueue.main.asyncAfter(deadline: .now() + seconds) { elapsed.fulfill() }
        wait(for: [elapsed], timeout: seconds + 2)
    }

    func testLateReadStillGetsTheDictationThenRestores() {
        // Chrome on a busy page services the ⌘V long after the minimum delay. Under the old fixed
        // timer it then pasted the user's previous clipboard; now the text waits for that read.
        ClipboardUtil.copyToClipboard("original", to: pasteboard)

        ClipboardUtil.borrowForPaste("transcription", on: pasteboard, restoreAfter: 0.05,
                                     readGrace: 0.05, unreadFallback: 5) {}

        spin(0.3)
        XCTAssertEqual(pasteboard.string(forType: .string), "transcription",
                       "a paste serviced after the minimum delay must still get the dictation")
        spin(0.3)
        XCTAssertEqual(pasteboard.string(forType: .string), "original",
                       "the read, not the five-second fallback, brings the clipboard back")
    }

    func testUnreadBorrowIsNotRestoredAtTheMinimumDelay() {
        ClipboardUtil.copyToClipboard("original", to: pasteboard)

        var borrowedCount = 0
        ClipboardUtil.borrowForPaste("transcription", on: pasteboard, restoreAfter: 0.05,
                                     unreadFallback: 0.6) {
            borrowedCount = pasteboard.changeCount
        }

        spin(0.3)
        // changeCount (not a string read, which would count as the paste) shows nothing restored.
        XCTAssertEqual(pasteboard.changeCount, borrowedCount)
        spin(0.6)
        XCTAssertEqual(pasteboard.string(forType: .string), "original")
    }

    func testEarlyReadStillWaitsForTheMinimumDelay() {
        // A clipboard manager that ignores the markers may read first; the restore never comes
        // sooner than the old fixed delay.
        ClipboardUtil.copyToClipboard("original", to: pasteboard)

        var borrowedCount = 0
        ClipboardUtil.borrowForPaste("transcription", on: pasteboard, restoreAfter: 0.4,
                                     readGrace: 0.01, unreadFallback: 5) {
            borrowedCount = pasteboard.changeCount
            _ = pasteboard.string(forType: .string)
        }

        spin(0.15)
        XCTAssertEqual(pasteboard.changeCount, borrowedCount)
        spin(0.5)
        XCTAssertEqual(pasteboard.string(forType: .string), "original")
    }

    func testOverlappingBorrowAfterAReadStillRestoresTheOriginal() {
        ClipboardUtil.copyToClipboard("original", to: pasteboard)

        ClipboardUtil.borrowForPaste("transcription A", on: pasteboard, restoreAfter: 0.05,
                                     readGrace: 0.05, unreadFallback: 5) {
            _ = pasteboard.string(forType: .string)
        }
        ClipboardUtil.borrowForPaste("transcription B", on: pasteboard, restoreAfter: 0.05,
                                     readGrace: 0.05, unreadFallback: 5) {
            _ = pasteboard.string(forType: .string)
        }

        spin(0.4)
        XCTAssertEqual(pasteboard.string(forType: .string), "original")
    }

    // MARK: - Overlapping borrows (#69 review)

    func testOverlappingBorrowsRestoreTheOriginalContents() {
        // Dictation borrows the clipboard, and before its restore fires the user re-pastes
        // (or a second dictation lands). The second borrow must NOT snapshot the first borrow's
        // transcription — it inherits the original snapshot, and the one surviving restore
        // brings back the user's contents.
        ClipboardUtil.copyToClipboard("original", to: pasteboard)

        ClipboardUtil.borrowForPaste("transcription A", on: pasteboard, restoreAfter: 0.05, unreadFallback: 0.05) {}
        ClipboardUtil.borrowForPaste("transcription B", on: pasteboard, restoreAfter: 0.05, unreadFallback: 0.05) {}

        let restoreWindowElapsed = expectation(description: "restore window elapsed")
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) { restoreWindowElapsed.fulfill() }
        wait(for: [restoreWindowElapsed], timeout: 2)
        XCTAssertEqual(pasteboard.string(forType: .string), "original",
                       "the second borrow must not end up restoring the first borrow's text")
    }

    func testManyOverlappingBorrowsStillRestoreTheOriginal() {
        ClipboardUtil.copyToClipboard("original", to: pasteboard)

        for n in 1...4 {
            ClipboardUtil.borrowForPaste("transcription \(n)", on: pasteboard, restoreAfter: 0.05, unreadFallback: 0.05) {}
        }

        let restoreWindowElapsed = expectation(description: "restore window elapsed")
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) { restoreWindowElapsed.fulfill() }
        wait(for: [restoreWindowElapsed], timeout: 2)
        XCTAssertEqual(pasteboard.string(forType: .string), "original")
    }

    func testUserCopyAfterOverlappingBorrowsStillWins() {
        // Newer content beats our restore even when borrows have coalesced.
        ClipboardUtil.copyToClipboard("original", to: pasteboard)

        ClipboardUtil.borrowForPaste("transcription A", on: pasteboard, restoreAfter: 0.05, unreadFallback: 0.05) {}
        ClipboardUtil.borrowForPaste("transcription B", on: pasteboard, restoreAfter: 0.05, unreadFallback: 0.05) {}
        ClipboardUtil.copyToClipboard("user copy in between", to: pasteboard)

        let restoreWindowElapsed = expectation(description: "restore window elapsed")
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) { restoreWindowElapsed.fulfill() }
        wait(for: [restoreWindowElapsed], timeout: 2)
        XCTAssertEqual(pasteboard.string(forType: .string), "user copy in between")
    }

    func testSequentialBorrowsDoNotInheritAStaleSnapshot() {
        // Once a borrow's restore has fired, the next borrow is a fresh cycle: it must snapshot
        // whatever is on the pasteboard NOW, not resurrect the coalescing state of the last one.
        ClipboardUtil.copyToClipboard("first original", to: pasteboard)
        ClipboardUtil.borrowForPaste("transcription A", on: pasteboard, restoreAfter: 0.05, unreadFallback: 0.05) {}

        let firstRestoreDone = expectation(description: "first restore done")
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) { firstRestoreDone.fulfill() }
        wait(for: [firstRestoreDone], timeout: 2)
        XCTAssertEqual(pasteboard.string(forType: .string), "first original")

        ClipboardUtil.copyToClipboard("second original", to: pasteboard)
        ClipboardUtil.borrowForPaste("transcription B", on: pasteboard, restoreAfter: 0.05, unreadFallback: 0.05) {}

        let secondRestoreDone = expectation(description: "second restore done")
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) { secondRestoreDone.fulfill() }
        wait(for: [secondRestoreDone], timeout: 2)
        XCTAssertEqual(pasteboard.string(forType: .string), "second original")
    }

    func testBorrowsOnDistinctPasteboardsDoNotShareSnapshots() {
        // Coalescing is per pasteboard: a pending borrow on one must not donate its snapshot
        // to a borrow on another.
        let other = NSPasteboard(name: NSPasteboard.Name("OpenSuperWhisperTests." + UUID().uuidString))
        defer { other.releaseGlobally() }
        ClipboardUtil.copyToClipboard("original A", to: pasteboard)
        ClipboardUtil.copyToClipboard("original B", to: other)

        ClipboardUtil.borrowForPaste("transcription", on: pasteboard, restoreAfter: 0.05, unreadFallback: 0.05) {}
        ClipboardUtil.borrowForPaste("transcription", on: other, restoreAfter: 0.05, unreadFallback: 0.05) {}

        let restoreWindowElapsed = expectation(description: "restore window elapsed")
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) { restoreWindowElapsed.fulfill() }
        wait(for: [restoreWindowElapsed], timeout: 2)
        XCTAssertEqual(pasteboard.string(forType: .string), "original A")
        XCTAssertEqual(other.string(forType: .string), "original B")
    }
}
